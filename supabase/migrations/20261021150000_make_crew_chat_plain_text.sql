-- Crew chat without end-to-end encryption.
--
-- Messages are now stored as text, readable by the crew's members and nobody
-- else through the API: the same row-level security as before, tied to crew
-- membership, plus TLS and Supabase's encryption at rest. Any device a member
-- signs in on reads the whole history, with no keys to hand between phones.
--
-- What was said under the old scheme is sealed with keys that live only on
-- the phones that held them, so it cannot be carried over and is dropped.

-- Departures only mattered for retiring keys.
drop trigger chat_member_left on public.crew_members;
drop function private.chat_member_left();
drop table private.chat_departures;
drop function public.chat_room(uuid);
drop function public.chat_pending_shares(uuid, uuid);

alter publication supabase_realtime drop table public.chat_key_shares;

delete from public.chat_messages;

-- The send rule checked the message's key, so it goes before the keys do.
drop policy chat_messages_send on public.chat_messages;
alter table public.chat_messages drop constraint chat_messages_deleted_empty;
alter table public.chat_messages
  drop column key_id,
  drop column nonce,
  drop column ciphertext,
  add column body text not null check (char_length(body) <= 2000),
  add constraint chat_messages_deleted_empty check (
    (deleted_at is null and btrim(body) <> '')
    or (deleted_at is not null and body = '')
  );
comment on column public.chat_messages.id is
  'Generated by the sender, so a retried send cannot land twice.';

create policy chat_messages_send on public.chat_messages for insert to authenticated
  with check (
    sender_id = (select auth.uid())
    and deleted_at is null
    and private.is_crew_member(crew_id, (select auth.uid()))
  );

drop table public.chat_key_shares;
drop table public.chat_keys;
drop table public.chat_devices;
drop function private.shares_crew(uuid, uuid);

-- Unsending empties the row rather than removing it, so everyone's list
-- closes the gap the same way and the realtime update says what happened.
create or replace function public.delete_chat_message(target_message_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  update public.chat_messages
  set deleted_at = now(), body = ''
  where id = target_message_id and sender_id = auth.uid() and deleted_at is null;
  if not found then
    raise exception 'Only the sender can delete a message' using errcode = '42501';
  end if;
end;
$$;

-- As before, but the push now says what was written: the crew's name as the
-- title, "Ana: running late" as the body.
create or replace function private.notify_chat_message() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  recipients uuid[];
  actor_name text;
  crew_name text;
  event uuid;
begin
  -- One sender's burst at a time per crew, so two messages landing together
  -- cannot both find the window empty.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('chat_push:' || new.crew_id, 0));

  select array_agg(m.user_id) into recipients
  from public.crew_members m
  where m.crew_id = new.crew_id and m.user_id <> new.sender_id
    -- Somebody who can be pushed to at all.
    and exists (
      select 1 from private.push_devices d
      join auth.sessions s on s.id = d.session_id and s.user_id = d.user_id
      where d.user_id = m.user_id and d.updated_at > now() - interval '60 days')
    -- Nobody already told about this crew's chat inside the window. Cancelled
    -- pushes, the ones they were reading anyway, do not count.
    and not exists (
      select 1 from private.notification_events e
      join private.notification_deliveries d on d.event_id = e.id
      where e.type = 'chat_message' and e.crew_id = new.crew_id
        and e.created_at > now() - private.chat_push_window()
        and d.recipient_id = m.user_id
        and d.status in ('pending', 'sending', 'sent'));
  if recipients is null then return new; end if;

  -- Display text only, never membership or delivery authorization.
  select coalesce(nullif(left(trim(first_name), 60), ''), 'A crew member')
    into actor_name from public.users where id = new.sender_id;
  select left(c.name, 60) into crew_name from public.crews c where c.id = new.crew_id;

  insert into private.notification_events(dedupe_key, type, crew_id, actor_id, payload)
  values ('chat_message:' || new.id, 'chat_message', new.crew_id, new.sender_id,
    jsonb_build_object(
      'actor_name', coalesce(actor_name, 'A crew member'),
      'crew_name', coalesce(crew_name, 'your crew'),
      'message_id', new.id,
      'sent_at', new.created_at,
      -- Enough for a lock screen; the chat has the rest.
      'text', left(new.body, 200)))
  on conflict (dedupe_key) do nothing returning id into event;
  if event is null then return new; end if;

  insert into private.notification_deliveries(event_id, device_id, recipient_id, available_at)
  select event, d.id, d.user_id, now() + private.chat_push_grace()
  from private.push_devices d
  join auth.sessions s on s.id = d.session_id and s.user_id = d.user_id
  where d.user_id = any(recipients) and d.updated_at > now() - interval '60 days';
  perform private.wake_notification_dispatcher();
  return new;
end;
$$;

-- An unsent message's words do not linger in the queue it left behind.
create function private.forget_unsent_chat_message() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update private.notification_events
  set payload = payload - 'text'
  where dedupe_key = 'chat_message:' || new.id;
  return new;
end;
$$;
revoke all on function private.forget_unsent_chat_message() from public, anon, authenticated;
create trigger chat_message_unsent after update of deleted_at on public.chat_messages
for each row when (old.deleted_at is null and new.deleted_at is not null)
execute function private.forget_unsent_chat_message();
